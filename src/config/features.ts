export const features = {
  /**
   * 계정 기능(가입·로그인·스크랩·월간 요약)을 여는가.
   *
   * **1차 공개에서는 꺼져 있다.** 이유는 이메일 확인이 아직 없기 때문이다 —
   * 확인 메일을 보낼 SMTP 가 없어 지금 가입을 열면 남의 주소로도 계정이 만들어지고
   * 비밀번호를 잊으면 복구할 방법이 없다 (D-42 가 남긴 상태). 2차에서 SMTP 와
   * 콜백 라우트가 붙으면 켠다.
   *
   * **코드를 지우지 않고 잠그는 이유**: 계정 기능은 이미 동작하는 상태로 다 있다
   * (Phase 1·6 에서 사람이 직접 눌러 확인했다). 지웠다가 2차에서 다시 쓰면
   * 검증된 코드를 버리는 것이다.
   *
   * **기본값이 꺼짐인 것도 의도적이다.** 환경변수를 빠뜨린 배포에서 가입이
   * 열려 있는 것보다 닫혀 있는 쪽이 안전하다.
   *
   * env: TECHNOW_ACCOUNTS=1
   */
  get accounts() {
    return process.env.TECHNOW_ACCOUNTS === '1';
  },
};
